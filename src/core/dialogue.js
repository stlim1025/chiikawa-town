const pick = (list, random) => list[Math.floor(random() * list.length) % list.length];

/** 말을 걸었을 때 첫 줄(친밀도 단계에 맞춰). 없는 친구면 null. */
export function greetingFor(kind, hearts, random = Math.random) {
  const g = GREET[kind];
  return g ? pick(g[tierOf(hearts)], random) : null;
}
/** '이야기하자' 대화 한 묶음: 지금 단계 70%, 앞 단계 30%(처음 단계는 friends.js 의 CHATS). */
export function chatFor(kind, hearts, random = Math.random) {
  const tier = tierOf(hearts), T = TALK[kind] || {};
  const pools = [CHATS[kind] || [['…']], T[2] || [], T[4] || []].slice(0, tier === 4 ? 3 : tier === 2 ? 2 : 1).filter((p) => p.length);
  const now = pools[pools.length - 1];
  const from = pools.length > 1 && random() >= 0.7 ? pools[Math.floor(random() * (pools.length - 1)) % (pools.length - 1)] : now;
  return pick(from, random);
}
